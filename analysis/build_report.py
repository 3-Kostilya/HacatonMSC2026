def num(x):
    return f"{int(x):,}".replace(",", " ")


def pct(n, d, digits=2):
    if not d:
        return "н/д"
    value = 100 * n / d
    unit = 10 ** (-digits)
    if 0 < value < unit / 2:
        return ("менее " + f"{unit:.{digits}f}%").replace(".", ",")
    if 100 - unit / 2 < value < 100:
        return ("более " + f"{100 - unit:.{digits}f}%").replace(".", ",")
    return f"{value:.{digits}f}%".replace(".", ",")


