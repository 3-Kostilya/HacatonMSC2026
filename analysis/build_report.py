def bars(labels, vals, title, color=TEAL, height=150, suffix=""):
    d = Drawing(W, height + 42)
    d.add(String(0, height + 27, title, fontName="Arial-Bold", fontSize=10, fillColor=INK))
    left, right, bottom = 45, W - 8, 25
    top = height + 8
    maximum = max(vals) * 1.18 if max(vals) else 1
    for fraction in [0, 0.25, 0.5, 0.75, 1]:
        y = bottom + (top - bottom) * fraction
        d.add(Line(left, y, right, y, strokeColor=LIGHT, strokeWidth=0.7))
        d.add(
            String(
                left - 6,
                y - 3,
                f"{maximum * fraction:.1f}",
                textAnchor="end",
                fontName="Arial",
                fontSize=7,
                fillColor=MUTED,
            )
        )
    step = (right - left) / len(vals)
    for i, (label, value) in enumerate(zip(labels, vals)):
        h = value / maximum * (top - bottom)
        x = left + i * step + step * 0.18
        d.add(Rect(x, bottom, step * 0.64, h, fillColor=color, strokeColor=None))
        d.add(
            String(
                x + step * 0.32,
                bottom + h + 5,
                f"{value:.1f}{suffix}",
                textAnchor="middle",
                fontName="Arial",
                fontSize=7.5,
                fillColor=INK,
            )
        )
        d.add(
            String(
                x + step * 0.32,
                10,
                str(label),
                textAnchor="middle",
                fontName="Arial",
                fontSize=7.5,
                fillColor=MUTED,
            )
        )
    story.append(d)
    story.append(Spacer(1, 8))


def monthly_chart():
    monthly = TOTAL["monthly"]["daily"]
    keys = list(monthly)
    values = [monthly[k] / 1e6 for k in keys]
    height, bottom, left, right = 192, 30, 40, W - 8
    d = Drawing(W, height + 25)
    maximum = max(values) * 1.12
    d.add(
        String(
            0,
            height + 13,
            "События по месяцам, млн строк",
            fontName="Arial-Bold",
            fontSize=10,
            fillColor=INK,
        )
    )
    for f in [0, 0.25, 0.5, 0.75, 1]:
        y = bottom + (height - bottom) * f
        d.add(Line(left, y, right, y, strokeColor=LIGHT))
        d.add(
            String(
                left - 5,
                y - 3,
                f"{maximum * f:.1f}",
                fontName="Arial",
                fontSize=7,
                textAnchor="end",
                fillColor=MUTED,
            )
        )
    points = []
    for i, (k, v) in enumerate(zip(keys, values)):
        x = left + i * (right - left) / (len(keys) - 1)
        points.extend([x, bottom + v / maximum * (height - bottom)])
        if k.endswith("-01") or i == 0:
            d.add(
                String(
                    x, 12, k[:4], fontName="Arial", fontSize=7, textAnchor="middle", fillColor=MUTED
                )
            )
    d.add(PolyLine(points, strokeColor=TEAL, strokeWidth=1.7))
    story.append(d)


